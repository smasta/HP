export const servicePath = (service: Service) =>
  `/${service.hub}/${service.slug}/`;

export const hubPath = (hub: HubKey) => `/${hub}/`;

export const findService = (hub: HubKey, slug: string) =>
  services.find((service) => service.hub === hub && service.slug === slug);

export const servicesOf = (hub: HubKey) =>
  services.filter((service) => service.hub === hub);

/** 関連サービスは同一ハブを優先し、見つからなければ全体から探す */
export const resolveRelated = (service: Service) =>
  service.related
    .map(
      (slug) =>
        findService(service.hub, slug) ??
        services.find((candidate) => candidate.slug === slug)
    )
    .filter((value): value is Service => Boolean(value));

